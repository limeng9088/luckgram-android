#!/usr/bin/env python3
"""Generate the Luckgram launcher icon resources from branding/icon-1024.png.

Writes (all densities):
  mipmap-*/ic_launcher.png, ic_launcher_round.png      legacy (pre-API 26) icons
  mipmap-*/luckgram_icon_foreground.png                adaptive foreground (108dp canvas)
  mipmap-*/luckgram_icon_monochrome.png                themed-icon mask (Android 13+)
  values/luckgram_icon.xml                             adaptive background colour
  mipmap-anydpi-v26/ic_launcher.xml, ic_launcher_round.xml

Run from the repo root: python3 branding/apply_icon.py   (needs Pillow)
"""
import os

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, 'TMessagesProj', 'src', 'main', 'res')
SRC = os.path.join(ROOT, 'branding', 'icon-1024.png')

# density -> (legacy icon px = 48dp, adaptive layer px = 108dp)
DENSITIES = {'mdpi': (48, 108), 'hdpi': (72, 162), 'xhdpi': (96, 216), 'xxhdpi': (144, 324), 'xxxhdpi': (192, 432)}
# Artwork occupies the 72dp visible area of the 108dp adaptive canvas.
ART_SCALE = 72 / 108
# Luminance thresholds for separating the artwork from the light background.
BG_LUM, FG_LUM = 238, 200

ADAPTIVE_XML = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by branding/apply_icon.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/luckgram_icon_background" />
    <foreground android:drawable="@mipmap/luckgram_icon_foreground" />
    <monochrome android:drawable="@mipmap/luckgram_icon_monochrome" />
</adaptive-icon>
'''


def background_color(img):
    """Average of the four corner pixels."""
    w, h = img.size
    px = [img.getpixel(p)[:3] for p in ((2, 2), (w - 3, 2), (2, h - 3), (w - 3, h - 3))]
    return tuple(sum(c[i] for c in px) // len(px) for i in range(3))


def keyed_artwork(img):
    """Artwork with the light background made transparent (soft edge by luminance)."""
    rgba = img.convert('RGBA')
    lum = img.convert('L')
    alpha = lum.point(lambda v: 0 if v >= BG_LUM else 255 if v <= FG_LUM else int(255 * (BG_LUM - v) / (BG_LUM - FG_LUM)))
    rgba.putalpha(alpha)
    return rgba


def on_canvas(art, size):
    """Center the artwork, scaled to the visible 72dp area, on a transparent 108dp canvas."""
    canvas = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    inner = round(size * ART_SCALE)
    scaled = art.resize((inner, inner), Image.LANCZOS)
    offset = (size - inner) // 2
    canvas.alpha_composite(scaled, (offset, offset))
    return canvas


def round_icon(img, size):
    base = img.convert('RGBA').resize((size, size), Image.LANCZOS)
    # Supersampled circular mask for a smooth edge.
    mask = Image.new('L', (size * 4, size * 4), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, size * 4 - 1, size * 4 - 1), fill=255)
    out = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    out.paste(base, (0, 0), mask.resize((size, size), Image.LANCZOS))
    return out


def main():
    src = Image.open(SRC).convert('RGB')
    assert src.size == (1024, 1024), src.size
    bg = background_color(src)
    art = keyed_artwork(src)
    # Monochrome: white glyph, alpha = artwork coverage.
    mono = Image.new('RGBA', art.size, (255, 255, 255, 0))
    mono.putalpha(art.getchannel('A'))

    for density, (legacy, layer) in DENSITIES.items():
        d = os.path.join(RES, 'mipmap-' + density)
        os.makedirs(d, exist_ok=True)
        src.resize((legacy, legacy), Image.LANCZOS).save(os.path.join(d, 'ic_launcher.png'), optimize=True)
        round_icon(src, legacy).save(os.path.join(d, 'ic_launcher_round.png'), optimize=True)
        on_canvas(art, layer).save(os.path.join(d, 'luckgram_icon_foreground.png'), optimize=True)
        on_canvas(mono, layer).save(os.path.join(d, 'luckgram_icon_monochrome.png'), optimize=True)

    with open(os.path.join(RES, 'values', 'luckgram_icon.xml'), 'w') as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by branding/apply_icon.py -->\n'
                '<resources>\n    <color name="luckgram_icon_background">#%02X%02X%02X</color>\n</resources>\n' % bg)
    for name in ('ic_launcher.xml', 'ic_launcher_round.xml'):
        with open(os.path.join(RES, 'mipmap-anydpi-v26', name), 'w') as f:
            f.write(ADAPTIVE_XML)
    print('background #%02X%02X%02X, %d densities written' % (bg + (len(DENSITIES),)))


if __name__ == '__main__':
    main()
