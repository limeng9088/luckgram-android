#!/usr/bin/env python3
"""Generate every Luckgram icon resource from one 1024x1024 source PNG.

    python3 branding/apply_icon.py [path/to/new-icon-1024.png]

With an argument the PNG is first copied to branding/icon-1024.png; without one the
existing branding/icon-1024.png is used. Run from anywhere; needs Pillow + numpy.

Source: a 1024x1024 app icon whose background is a linear gradient (or flat colour),
optionally with transparent rounded corners, and a light glyph on top. The script
fits the gradient, then splits the art into a background layer (gradient, extended
to full bleed) and a foreground layer (glyph), so the Android adaptive icon gets real
layers and the notification icon gets a clean silhouette.

Writes (TMessagesProj/src/main/res):
  mipmap-*/ic_launcher.png, ic_launcher_round.png        legacy icons (48dp)
  mipmap-*/luckgram_icon_{background,foreground,monochrome}.png   adaptive layers (108dp)
  mipmap-anydpi-v26/ic_launcher.xml, ic_launcher_round.xml
  mipmap-*/icon*_foreground_sa.png                       in-app icon previews (were Telegram's plane)
  drawable-*/notification.png                            status-bar small icon (24dp, white)
  drawable-*/ic_launcher_dr.png                          shortcut / call person icon (48dp, round)
  drawable-*/logo_middle.png                             terms-of-service logo (68dp)
  drawable-nodpi/luckgram_qr_logo.png                    QR-code centre logo
  branding/play-store-512.png                            Google Play hi-res icon
  branding/preview.png                                   contact sheet for review
"""
import glob
import os
import shutil
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BRAND = os.path.join(ROOT, 'branding')
RES = os.path.join(ROOT, 'TMessagesProj', 'src', 'main', 'res')
SRC = os.path.join(BRAND, 'icon-1024.png')

DENSITY = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}
ART_SCALE = 72 / 108  # the source square fills the 72dp visible part of the 108dp adaptive canvas
NOTIF_LIVE = 20 / 24  # small icon glyph fits a 20dp live area inside 24dp

ADAPTIVE_XML = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by branding/apply_icon.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/luckgram_icon_background" />
    <foreground android:drawable="@mipmap/luckgram_icon_foreground" />
    <monochrome android:drawable="@mipmap/luckgram_icon_monochrome" />
</adaptive-icon>
'''


# ---------------------------------------------------------------- layer split
# Kept identical in luckgram-ios/branding/apply_icon.py.

class Layers:
    """Background gradient model + foreground glyph extracted from the source icon."""

    def __init__(self, img):
        rgba = np.asarray(img.convert('RGBA'), dtype=np.float64)
        n = rgba.shape[0]
        rgb, a = rgba[..., :3], rgba[..., 3]
        v, u = np.mgrid[0:n, 0:n] / (n - 1)
        design = np.stack([np.ones_like(u), u, v], -1).reshape(-1, 3)
        # Fit colour = c0 + cu*u + cv*v on opaque pixels, dropping the glyph as outliers.
        # Trimmed least squares: repeatedly keep the best-fitting 80% (the glyph drops out).
        opaque = (a == 255).reshape(-1)
        mask = opaque
        for i in range(10):
            coef, *_ = np.linalg.lstsq(design[mask], rgb.reshape(-1, 3)[mask], rcond=None)
            resid = np.linalg.norm(design @ coef - rgb.reshape(-1, 3), axis=1)
            thr = max(12.0, np.percentile(resid[mask], 80)) if i < 8 else 12.0
            mask = opaque & (resid < thr)
        self.coef = coef
        self.size = n
        if mask.mean() < 0.3 or np.median(resid[mask]) > 4:
            sys.exit('source background is not a linear gradient / flat colour; cannot split layers')

        bg = (design @ coef).reshape(n, n, 3)
        diff = np.linalg.norm(rgb - bg, axis=-1)
        diff[a < 255] = 0  # rounded-corner anti-aliasing is background, not glyph
        core = diff > 60
        # Anti-aliased glyph edge: coverage = diff / diff of the nearest solid glyph pixel.
        near = np.asarray(Image.fromarray(np.clip(diff * core, 0, 255).astype(np.uint8)).filter(
            ImageFilter.MaxFilter(7)), dtype=np.float64)
        alpha = np.where(core, 1.0, np.where(near > 60, np.clip(diff / np.maximum(near, 1), 0, 1), 0.0))
        alpha[alpha < 0.06] = 0
        color = bg + (rgb - bg) / np.maximum(alpha, 1e-6)[..., None]  # un-mix the old background
        fg = np.dstack([np.clip(color, 0, 255), alpha * 255]).round().astype(np.uint8)
        self.fg = Image.fromarray(fg, 'RGBA')
        if alpha.sum() < n * n * 0.01:
            sys.exit('no foreground glyph found (glyph must contrast with the background)')

    def background(self, size, lo=0.0, hi=1.0):
        """Gradient rendered at size x size, covering source coordinates lo..hi (may extrapolate)."""
        t = lo + (np.arange(size) + 0.5) / size * (hi - lo)
        v, u = np.meshgrid(t, t, indexing='ij')
        rgb = np.stack([np.ones_like(u), u, v], -1) @ self.coef
        return Image.fromarray(np.clip(rgb, 0, 255).round().astype(np.uint8), 'RGB').convert('RGBA')

    def square(self, size):
        """Opaque full-bleed icon (no rounded corners)."""
        out = self.background(self.size)
        out.alpha_composite(self.fg)
        return out.resize((size, size), Image.LANCZOS)

    def silhouette(self):
        """White glyph, alpha = coverage."""
        out = Image.new('RGBA', self.fg.size, (255, 255, 255, 0))
        out.putalpha(self.fg.getchannel('A'))
        return out


def circle(img):
    size = img.size[0]
    mask = Image.new('L', (size * 4, size * 4), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, size * 4 - 1, size * 4 - 1), fill=255)
    out = Image.new('RGBA', img.size, (0, 0, 0, 0))
    out.paste(img, (0, 0), mask.resize(img.size, Image.LANCZOS))
    return out


def centered(art, size, scale):
    canvas = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    inner = round(size * scale)
    off = (size - inner) // 2
    canvas.alpha_composite(art.resize((inner, inner), Image.LANCZOS), (off, off))
    return canvas


def fit_bbox(art, size, live):
    """Crop to the glyph's bounding box and fit it (aspect kept) into live*size, centered."""
    glyph = art.crop(art.getchannel('A').getbbox())
    box = size * live
    k = box / max(glyph.size)
    glyph = glyph.resize((max(1, round(glyph.width * k)), max(1, round(glyph.height * k))), Image.LANCZOS)
    canvas = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    canvas.alpha_composite(glyph, ((size - glyph.width) // 2, (size - glyph.height) // 2))
    return canvas


# ---------------------------------------------------------------- android

def px(dp, density):
    return round(dp * DENSITY[density])


def save(img, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    stem = os.path.splitext(path)[0]
    for old in glob.glob(stem + '.*'):  # a .webp/.png twin would be a duplicate resource
        if old != path:
            os.remove(old)
    img.save(path, optimize=True)


def main():
    if len(sys.argv) > 1:
        shutil.copyfile(sys.argv[1], SRC)
    src = Image.open(SRC).convert('RGBA')
    assert src.size == (1024, 1024), 'source must be 1024x1024, got %s' % (src.size,)
    L = Layers(src)
    full = L.square(1024)
    white = L.silhouette()
    written = 0

    for d in DENSITY:
        mip = os.path.join(RES, 'mipmap-' + d)
        legacy, layer = px(48, d), px(108, d)
        save(src.resize((legacy, legacy), Image.LANCZOS), os.path.join(mip, 'ic_launcher.png'))
        save(circle(full.resize((legacy, legacy), Image.LANCZOS)), os.path.join(mip, 'ic_launcher_round.png'))
        save(L.background(layer, -0.25, 1.25), os.path.join(mip, 'luckgram_icon_background.png'))
        fg = centered(L.fg, layer, ART_SCALE)
        save(fg, os.path.join(mip, 'luckgram_icon_foreground.png'))
        save(centered(white, layer, ART_SCALE), os.path.join(mip, 'luckgram_icon_monochrome.png'))
        written += 5
        # Telegram's in-app icon previews (app-icon picker, Premium page) drew its own plane.
        for f in glob.glob(os.path.join(mip, 'icon*_foreground_sa.png')):
            save(fg, f)
            written += 1

        drw = os.path.join(RES, 'drawable-' + d)
        save(fit_bbox(white, px(24, d), NOTIF_LIVE), os.path.join(drw, 'notification.png'))
        save(circle(full.resize((legacy, legacy), Image.LANCZOS)), os.path.join(drw, 'ic_launcher_dr.png'))
        save(src.resize((px(68, d),) * 2, Image.LANCZOS), os.path.join(drw, 'logo_middle.png'))
        written += 3

    for name in ('ic_launcher.xml', 'ic_launcher_round.xml'):
        with open(os.path.join(RES, 'mipmap-anydpi-v26', name), 'w') as f:
            f.write(ADAPTIVE_XML)
    old_color = os.path.join(RES, 'values', 'luckgram_icon.xml')  # previous version used a flat colour
    if os.path.exists(old_color):
        os.remove(old_color)

    # QR-code centre logo (QR sheets, own QR page, update screen); was Telegram's plane.
    save(circle(full.resize((288, 288), Image.LANCZOS)), os.path.join(RES, 'drawable-nodpi', 'luckgram_qr_logo.png'))
    full.convert('RGB').resize((512, 512), Image.LANCZOS).save(os.path.join(BRAND, 'play-store-512.png'), optimize=True)
    preview(L, src, full, white)
    print('%d resources written; background gradient fitted, glyph coverage %.1f%%'
          % (written, 100 * np.asarray(L.fg.getchannel('A')).mean() / 255))


def preview(L, src, full, white):
    """branding/preview.png: legacy | round | adaptive (squircle mask) | themed | notification."""
    cell, pad = 192, 16
    adaptive = L.background(cell, -0.25, 1.25)
    adaptive.alpha_composite(centered(L.fg, cell, ART_SCALE))
    m = Image.new('L', (cell * 4,) * 2, 0)
    ImageDraw.Draw(m).rounded_rectangle((cell * 2 // 3, cell * 2 // 3, cell * 10 // 3, cell * 10 // 3), radius=cell * 2 // 3, fill=255)
    adaptive_masked = Image.new('RGBA', (cell, cell), (0, 0, 0, 0))
    adaptive_masked.paste(adaptive, (0, 0), m.resize((cell, cell), Image.LANCZOS))
    themed = Image.new('RGBA', (cell, cell), (40, 52, 64, 255))
    themed.alpha_composite(centered(white, cell, ART_SCALE))
    notif = Image.new('RGBA', (cell, cell), (32, 32, 32, 255))
    notif.alpha_composite(fit_bbox(white, 24, NOTIF_LIVE).resize((96, 96), Image.NEAREST), (48, 48))
    tiles = [src.resize((cell, cell), Image.LANCZOS), circle(full.resize((cell, cell), Image.LANCZOS)),
             adaptive_masked, themed, notif]
    sheet = Image.new('RGBA', (len(tiles) * (cell + pad) + pad, cell + 2 * pad), (230, 232, 235, 255))
    for i, t in enumerate(tiles):
        sheet.alpha_composite(t, (pad + i * (cell + pad), pad))
    sheet.convert('RGB').save(os.path.join(BRAND, 'preview.png'), optimize=True)


if __name__ == '__main__':
    main()
